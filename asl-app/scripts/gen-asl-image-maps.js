const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'assets', 'asl');
const constantsDir = path.join(__dirname, '..', 'constants');

/** Module folder under assets/asl -> learning module id (same name). */
const VOCAB_MODULES = [
  'conversation',
  'wh-questions',
  'emotions',
  'animals',
  'food',
  'body-parts',
  'work',
  'internet',
  'school',
  'sports',
];

function listPngIds(dir) {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) {
    return [];
  }

  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith('.png'))
    .sort((a, b) => {
      const aId = a.replace(/\.png$/i, '');
      const bId = b.replace(/\.png$/i, '');
      if (/^\d+$/.test(aId) && /^\d+$/.test(bId)) {
        return Number(aId) - Number(bId);
      }
      return aId.localeCompare(bId);
    })
    .map((f) => f.replace(/\.png$/i, ''));
}

function entryLines(dir, ids) {
  return ids
    .map((id) => `  '${id}': require('../assets/asl/${dir}/${id}.png'),`)
    .join('\n');
}

function writeSimpleMap(fileName, exportName, dir) {
  const ids = listPngIds(dir);
  const body = `import type { ImageSourcePropType } from 'react-native';

export const ${exportName}: Record<string, ImageSourcePropType> = {
${entryLines(dir, ids)}
};
`;
  const out = path.join(constantsDir, fileName);
  fs.writeFileSync(out, body);
  console.log('wrote', out, `(${ids.length} images)`);
}

function writeModuleMap() {
  const blocks = VOCAB_MODULES.map((moduleId) => {
    const ids = listPngIds(moduleId);
    const lines =
      ids.length === 0
        ? ''
        : `\n${ids
            .map(
              (id) =>
                `    '${id}': require('../assets/asl/${moduleId}/${id}.png'),`,
            )
            .join('\n')}\n  `;
    return `  '${moduleId}': {${lines}},`;
  }).join('\n');

  const body = `import type { ImageSourcePropType } from 'react-native';

/**
 * Drop-in PNG maps for vocab modules.
 * Generated by scripts/gen-asl-image-maps.js. Do not edit by hand.
 * Add \`assets/asl/{module}/{signId}.png\` then re-run the script.
 */
export const MODULE_IMAGES: Record<
  string,
  Record<string, ImageSourcePropType>
> = {
${blocks}
};
`;

  const out = path.join(constantsDir, 'aslModuleImages.ts');
  fs.writeFileSync(out, body);
  const total = VOCAB_MODULES.reduce(
    (sum, id) => sum + listPngIds(id).length,
    0,
  );
  console.log('wrote', out, `(${total} vocab images across modules)`);
}

writeSimpleMap('aslLetterImages.ts', 'LETTER_IMAGES', 'letters');
writeSimpleMap('aslNumberImages.ts', 'NUMBER_IMAGES', 'numbers');
writeModuleMap();
